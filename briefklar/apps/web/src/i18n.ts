const DICTS: Partial<Record<LanguageCode, UiStrings>> = { de, en, tr, ar, uk, ru };

let current: LanguageCode = "de";

/** Sprache, in der die UI tatsächlich angezeigt wird (mit Fallback auf Deutsch). */
export function uiLanguage(): LanguageCode {
  return DICTS[current] ? current : "en";
}

export function hasUiTranslation(code: LanguageCode): boolean {
  return Boolean(DICTS[code]);
}

/** Setzt die gewünschte UI-Sprache und aktualisiert <html lang/dir>. */
export function setUiLanguage(code: LanguageCode): void {
  current = code;
  const ui = uiLanguage();
  document.documentElement.lang = ui;
  document.documentElement.dir = isRtl(ui) ? "rtl" : "ltr";
}

export function t(key: UiKey, vars?: Record<string, string | number>): string {
  const dict = DICTS[current] ?? en;
  let s = dict[key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** BCP-47-Tag für Intl / Sprachausgabe */
export function bcp47(code: LanguageCode): string {
  const map: Partial<Record<LanguageCode, string>> = {
    de: "de-DE", en: "en-GB", tr: "tr-TR", ar: "ar", uk: "uk-UA", ru: "ru-RU", pl: "pl-PL",
    ro: "ro-RO", fa: "fa-IR", ps: "ps-AF", ku: "ku", ckb: "ckb", it: "it-IT", es: "es-ES",
    fr: "fr-FR", pt: "pt-PT", el: "el-GR", hr: "hr-HR", sr: "sr-Latn", bs: "bs-BA", sq: "sq-AL",
    mk: "mk-MK", bg: "bg-BG", hu: "hu-HU", cs: "cs-CZ", sk: "sk-SK", nl: "nl-NL", lt: "lt-LT",
    vi: "vi-VN", zh: "zh-CN", th: "th-TH", tl: "fil-PH", ur: "ur-PK", hi: "hi-IN", pa: "pa-IN",
    bn: "bn-BD", ta: "ta-IN", ti: "ti-ER", am: "am-ET", so: "so-SO", sw: "sw-KE", ha: "ha-NG",
    ka: "ka-GE", hy: "hy-AM", az: "az-AZ", he: "he-IL", ja: "ja-JP", ko: "ko-KR",
  };
  return map[code] ?? code;
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  const kb = bytes / 1024;
  if (kb < 1024) return `${Math.round(kb)} KB`;
  const mb = kb / 1024;
  return `${mb.toLocaleString(bcp47(uiLanguage()), { maximumFractionDigits: 1 })} MB`;
}

/** ISO-Datum (YYYY-MM-DD) hübsch formatieren; unbekannte Formate unverändert zurückgeben. */
export function formatDate(iso: string, lang: LanguageCode): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
  if (!m) return iso;
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])));
  if (Number.isNaN(d.getTime())) return iso;
  try {
    return new Intl.DateTimeFormat(bcp47(lang), { dateStyle: "long", timeZone: "UTC" }).format(d);
  } catch {
    return iso;
  }
}
